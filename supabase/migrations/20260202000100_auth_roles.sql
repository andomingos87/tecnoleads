create extension if not exists "pgcrypto";

do $$
begin
  if not exists (select 1 from pg_type where typname = 'app_role') then
    create type public.app_role as enum (
      'dev',
      'admin',
      'diretoria',
      'gerente',
      'gerente_marketing',
      'gestor_trafego',
      'vendedor',
      'pre_venda'
    );
  end if;
end $$;

do $$
begin
  if not exists (select 1 from pg_type where typname = 'lead_status') then
    create type public.lead_status as enum ('novo', 'em_contato', 'cliente', 'inativo');
  end if;
end $$;

do $$
begin
  if not exists (select 1 from pg_type where typname = 'opportunity_status') then
    create type public.opportunity_status as enum (
      'orcamento',
      'negociacao',
      'ganho',
      'perdido'
    );
  end if;
end $$;

create table if not exists public.profiles (
  id uuid primary key references auth.users on delete cascade,
  role public.app_role not null default 'vendedor',
  full_name text,
  email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.login_history (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users on delete cascade,
  logged_at timestamptz not null default now(),
  ip_address text,
  user_agent text
);

create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  manager_id uuid references auth.users,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.team_members (
  team_id uuid not null references public.teams on delete cascade,
  user_id uuid not null references auth.users on delete cascade,
  created_at timestamptz not null default now(),
  primary key (team_id, user_id)
);

create table if not exists public.leads (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text,
  phone text,
  city text,
  state text,
  origin text,
  owner_id uuid references auth.users,
  status public.lead_status not null default 'novo',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.opportunities (
  id uuid primary key default gen_random_uuid(),
  lead_id uuid references public.leads on delete cascade,
  segment text not null,
  product text not null,
  stage public.opportunity_status not null default 'orcamento',
  owner_id uuid references auth.users,
  amount numeric(12, 2) not null default 0,
  budget_number bigint generated by default as identity,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (budget_number)
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

